"""Regenerate ``pno/data/countries.toml``.

Development-only helper. It collects the country codes Proton VPN can use and
the codes Arch Linux mirrors use, then renders English and Ukrainian names
from CLDR (via Babel). The generated file is committed; the runtime package
does not depend on Babel.

Usage::

    .venv/bin/python tools/gen_countries.py
"""

from __future__ import annotations

import argparse
import json
import urllib.request
from pathlib import Path

try:
    from babel import Locale
except ImportError:  # pragma: no cover - developer convenience
    raise SystemExit("install the 'tools' extra first: pip install -e '.[tools]'")

PROTON_FALLBACK_CODES = """
AD AE AF AL AM AO AR AT AU AZ BA BD BE BG BH BN BO BR BT BY CA CD CH CI CL CM
CN CO CR CU CY CZ DE DK DO DZ EC EE EG ER ES ET FI FR GA GE GH GL GN GR GT HK
HN HR HT HU ID IE IL IN IQ IS IT JM JO JP KE KG KH KM KR KW KZ LA LB LI LK LT
LU LV LY MA MC MD ME MK MM MN MO MR MT MU MX MY MZ NG NI NL NO NP NZ OM PA PE
PG PH PK PL PR PS PT PY QA RO RS RU RW SA SD SE SG SI SK SN SO SS SV SY TD TG
TH TJ TM TN TR TW TZ UA UG UK US UY UZ VE VN XK YE ZA ZW
""".split()

PROTON_CACHE = Path.home() / ".cache" / "Proton" / "VPN" / "serverlist.json"
MIRROR_STATUS_URL = "https://archlinux.org/mirrors/status/json/"
OUTPUT = Path(__file__).resolve().parents[1] / "pno" / "data" / "countries.toml"

ALIASES = {"UK": "GB"}


def proton_codes() -> set[str]:
    codes = set(PROTON_FALLBACK_CODES)
    try:
        payload = json.loads(PROTON_CACHE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return codes
    for server in payload.get("LogicalServers", []):
        for key in ("EntryCountry", "ExitCountry"):
            value = server.get(key)
            if value:
                codes.add(value)
    return codes


def arch_codes(source: str | None) -> set[str]:
    try:
        if source:
            raw = Path(source).read_bytes()
        else:
            with urllib.request.urlopen(MIRROR_STATUS_URL, timeout=30) as response:
                raw = response.read()
        payload = json.loads(raw)
        return {
            mirror["country_code"]
            for mirror in payload.get("urls", [])
            if mirror.get("country_code")
        }
    except (OSError, ValueError) as exc:
        raise SystemExit(f"cannot read mirror status: {exc}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mirrors-json", help="offline copy of mirrors/status/json")
    args = parser.parse_args()

    english = Locale.parse("en")
    ukrainian = Locale.parse("uk")
    codes = proton_codes() | arch_codes(args.mirrors_json)
    inverse_aliases = set(ALIASES)

    lines = [
        "# Generated by tools/gen_countries.py — do not edit by hand.",
        "# Proton VPN and Arch Linux country codes with EN/UK display names.",
        "",
        "[aliases]",
    ]
    for alias, target in sorted(ALIASES.items()):
        lines.append(f'{alias} = "{target}"')
    lines.append("")

    missing: list[str] = []
    for code in sorted(codes):
        if code in inverse_aliases:
            continue
        en = english.territories.get(code)
        uk = ukrainian.territories.get(code)
        if not en or not uk:
            missing.append(code)
            continue
        lines.append(f"[countries.{code}]")
        lines.append(f'en = "{_escape(en)}"')
        lines.append(f'uk = "{_escape(uk)}"')
        lines.append("")

    if missing:
        lines.append("# Codes without CLDR names (kept as-is at runtime):")
        lines.append("# " + ", ".join(sorted(missing)))

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(codes) - len(missing)} named codes)")
    if missing:
        print("missing CLDR names:", ", ".join(sorted(missing)))


def _escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


if __name__ == "__main__":
    main()
