"""Install and uninstall the user service, tray autostart and sudo helper."""

from __future__ import annotations

import getpass
import os
import shutil
import subprocess
import sys
import tempfile
from importlib import resources
from pathlib import Path
from typing import Any

from pno import config as config_module
from pno import events, paths
from pno.config import Config
from pno.errors import PnoError
from pno.mirrors.apply import HELPER_LOCATIONS
from pno.state import atomic_write_text

HELPER_TARGET = HELPER_LOCATIONS[0]
SUDOERS_FILE = Path("/etc/sudoers.d/pno-mirror")
UNIT_NAME = "pno-daemon.service"
AUTOSTART_NAME = "pno-tray.desktop"
DESKTOP_NAME = "proton-net-optimizer.desktop"
ICON_NAME = "proton-net-optimizer.svg"
BACKUP_DIR = "/var/lib/pno"


def repo_root() -> Path:
    candidate = Path(__file__).resolve().parents[1]
    if (candidate / "pyproject.toml").is_file():
        return candidate
    return Path.home()


def _template(name: str) -> str:
    target = resources.files("pno").joinpath(f"data/{name}")
    return target.read_text(encoding="utf-8")


def desktop_dir() -> Path:
    return Path.home() / ".local" / "share" / "applications"


def icon_dir() -> Path:
    return Path.home() / ".local" / "share" / "icons" / "hicolor" / "scalable" / "apps"


def desktop_path() -> Path:
    return desktop_dir() / DESKTOP_NAME


def icon_path() -> Path:
    return icon_dir() / ICON_NAME


def _write_if_changed(path: Path, content: str, *, mode: int = 0o644) -> bool:
    try:
        current = path.read_text(encoding="utf-8")
    except OSError:
        current = ""
    if current == content:
        return False
    atomic_write_text(path, content, mode=mode)
    return True


def _sudo(command: list[str], *, timeout: float = 120.0) -> subprocess.CompletedProcess:
    try:
        completed = subprocess.run(
            ["sudo", *command],
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise PnoError("sudo command failed to start", detail=str(exc)) from exc
    if completed.returncode != 0:
        raise PnoError(
            f"sudo {' '.join(command)} failed",
            detail=(completed.stderr or completed.stdout)[-500:],
        )
    return completed


def _systemctl(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    try:
        completed = subprocess.run(
            ["systemctl", "--user", *args],
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise PnoError("systemctl --user failed", detail=str(exc)) from exc
    if check and completed.returncode != 0:
        raise PnoError(
            f"systemctl --user {' '.join(args)} failed",
            detail=(completed.stderr or completed.stdout)[-500:],
        )
    return completed


def _confirm(question: str, *, assume_yes: bool) -> bool:
    if assume_yes:
        return True
    try:
        answer = input(f"{question} [y/N] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        return False
    return answer in {"y", "yes"}


def _sudoers_content(user: str, mirrorlist: str) -> str:
    common = (
        f"{user} ALL=(root) NOPASSWD: {HELPER_TARGET} "
        f"--path {mirrorlist} --backup-dir {BACKUP_DIR}"
    )
    return (
        "# Generated by proton-net-optimizer. Remove with 'pno uninstall'.\n"
        f"{common}\n"
        f"{common} --pacman-sync\n"
    )


def _refresh_desktop_caches() -> list[str]:
    """Refresh KDE/GNOME caches so the new entry appears immediately."""
    commands = [
        ["update-desktop-database", str(desktop_dir())],
        ["gtk-update-icon-cache", "-f", "-t", str(icon_dir().parents[1])],
        ["kbuildsycoca6", "--noincremental"],
    ]
    ran: list[str] = []
    for command in commands:
        if not shutil.which(command[0]):
            continue
        try:
            subprocess.run(
                command,
                capture_output=True,
                text=True,
                timeout=60,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        ran.append(command[0])
    return ran


def _install_desktop(python: str) -> dict[str, Any]:
    desktop_dir().mkdir(parents=True, exist_ok=True)
    icon_dir().mkdir(parents=True, exist_ok=True)
    desktop_text = _template(DESKTOP_NAME).format(python=python)
    icon_text = _template(ICON_NAME)
    result = {
        "desktop": str(desktop_path()),
        "desktop_changed": _write_if_changed(desktop_path(), desktop_text),
        "icon": str(icon_path()),
        "icon_changed": _write_if_changed(icon_path(), icon_text),
    }
    result["caches"] = _refresh_desktop_caches()
    return result


def _install_helper(
    *,
    user: str,
    config: Config,
    assume_yes: bool,
    no_sudo: bool,
) -> dict[str, Any]:
    result: dict[str, Any] = {"installed": False, "sudoers": False}
    if no_sudo:
        result["reason"] = "disabled with --no-sudo"
        return result
    if not _confirm(
        f"Install {HELPER_TARGET} and a NOPASSWD sudoers rule for automatic "
        "mirror updates?",
        assume_yes=assume_yes,
    ):
        result["reason"] = "declined"
        return result

    source = resources.files("pno").joinpath("mirrors/apply_helper.py")
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", delete=False) as handle:
        handle.write(source.read_text(encoding="utf-8"))
        source_path = handle.name
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", delete=False) as handle:
        handle.write(_sudoers_content(user, config.mirrorlist_path))
        sudoers_tmp = handle.name
    try:
        _sudo(
            [
                "install",
                "-D",
                "-m",
                "0755",
                "-o",
                "root",
                "-g",
                "root",
                source_path,
                str(HELPER_TARGET),
            ]
        )
        _sudo(
            [
                "install",
                "-m",
                "0440",
                "-o",
                "root",
                "-g",
                "root",
                sudoers_tmp,
                str(SUDOERS_FILE),
            ]
        )
        _sudo(["visudo", "-cf", str(SUDOERS_FILE)])
    finally:
        for path in (source_path, sudoers_tmp):
            try:
                os.unlink(path)
            except OSError:
                pass
    result.update(installed=True, sudoers=True)
    return result


def install(
    *,
    assume_yes: bool = False,
    no_sudo: bool = False,
    no_start: bool = False,
) -> dict[str, Any]:
    config = config_module.ensure()
    events.configure_from_config(config)
    events.emit("info", "install", "install.start", {"user": getpass.getuser()})
    result: dict[str, Any] = {"config": str(paths.config_file())}

    unit_dir = Path.home() / ".config" / "systemd" / "user"
    unit_dir.mkdir(parents=True, exist_ok=True)
    unit_text = _template("pno-daemon.service").format(
        python=sys.executable, repo_root=repo_root()
    )
    unit_path = unit_dir / UNIT_NAME
    result["unit"] = str(unit_path)
    result["unit_changed"] = _write_if_changed(unit_path, unit_text)

    autostart_dir = Path.home() / ".config" / "autostart"
    autostart_dir.mkdir(parents=True, exist_ok=True)
    autostart_text = _template("pno-tray.desktop").format(python=sys.executable)
    autostart_path = autostart_dir / AUTOSTART_NAME
    result["autostart"] = str(autostart_path)
    result["autostart_changed"] = _write_if_changed(autostart_path, autostart_text)

    desktop = _install_desktop(sys.executable)
    result["desktop"] = desktop["desktop"]
    result["desktop_changed"] = desktop["desktop_changed"]
    result["icon"] = desktop["icon"]
    result["icon_changed"] = desktop["icon_changed"]

    try:
        _systemctl("daemon-reload")
        if not no_start:
            _systemctl("enable", "--now", UNIT_NAME)
            result["service"] = "enabled and started"
        else:
            _systemctl("enable", UNIT_NAME)
            result["service"] = "enabled (not started)"
    except PnoError as exc:
        result["service"] = f"error: {exc.message}"
        result.setdefault("errors", []).append(exc.message)

    try:
        result["helper"] = _install_helper(
            user=getpass.getuser(),
            config=config,
            assume_yes=assume_yes,
            no_sudo=no_sudo,
        )
    except PnoError as exc:
        result["helper"] = {"installed": False, "error": exc.to_dict()}

    events.emit(
        "info",
        "install",
        "install.done",
        {key: value for key, value in result.items() if key != "helper"},
    )
    return result


def uninstall(
    *,
    assume_yes: bool = False,
    purge: bool = False,
) -> dict[str, Any]:
    config = config_module.load()
    events.configure_from_config(config)
    events.emit("info", "install", "uninstall.start")
    result: dict[str, Any] = {}

    _systemctl("disable", "--now", UNIT_NAME, check=False)
    unit_path = Path.home() / ".config" / "systemd" / "user" / UNIT_NAME
    autostart_path = Path.home() / ".config" / "autostart" / AUTOSTART_NAME
    for path in (unit_path, autostart_path, desktop_path(), icon_path()):
        try:
            path.unlink()
            result.setdefault("removed", []).append(str(path))
        except FileNotFoundError:
            pass
        except OSError as exc:
            result.setdefault("errors", []).append(f"{path}: {exc}")
    _systemctl("daemon-reload", check=False)
    _refresh_desktop_caches()

    if SUDOERS_FILE.exists() or HELPER_TARGET.exists():
        if _confirm("Remove the sudo helper and sudoers rule?", assume_yes=assume_yes):
            for target in (str(SUDOERS_FILE), str(HELPER_TARGET)):
                try:
                    _sudo(["rm", "-f", target])
                except PnoError as exc:
                    result.setdefault("errors", []).append(exc.message)
            result["helper_removed"] = True

    if purge:
        for directory in (paths.config_dir(), paths.state_dir()):
            try:
                shutil.rmtree(directory)
                result.setdefault("removed", []).append(str(directory))
            except FileNotFoundError:
                pass
            except OSError as exc:
                result.setdefault("errors", []).append(f"{directory}: {exc}")
    result["purged"] = purge
    events.emit("info", "install", "uninstall.done", {"purged": purge})
    return result
