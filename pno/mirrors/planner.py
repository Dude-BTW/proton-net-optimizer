"""Build a mirror plan from measurements.

Ordering is derived exclusively from runtime data: Arch's score only narrows
the candidate set, and the final order comes from measured latency.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from typing import Any, Callable, Iterable

from pno import events
from pno.config import Config
from pno.countries import country_name, normalize_code
from pno.errors import ProbeError
from pno.mirrors.models import Mirror, MirrorStatusSnapshot, ProbeResult
from pno.mirrors.probe import probe_many
from pno.mirrors.status import eligible_mirrors, mirrors_for_country

SERVER_PREFIX = "Server = "


@dataclass
class MirrorPlan:
    target_country: str
    target_source: str
    candidates: list[ProbeResult]
    selected: list[Mirror]
    content: str
    measured_at: float
    reason: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "target_country": self.target_country,
            "target_source": self.target_source,
            "measured_at": self.measured_at,
            "reason": self.reason,
            "selected": [mirror.to_dict() for mirror in self.selected],
            "candidates": [result.to_dict() for result in self.candidates],
        }

    @property
    def server_lines(self) -> list[str]:
        return server_lines(self.content)


def server_lines(content: str) -> list[str]:
    lines: list[str] = []
    for raw in content.splitlines():
        line = raw.strip()
        if line.startswith(SERVER_PREFIX):
            lines.append(line)
    return lines


def same_server_set(first: str, second: str) -> bool:
    return server_lines(first) == server_lines(second)


def _dedupe_candidates(candidates: Iterable[Mirror]) -> list[Mirror]:
    seen: set[str] = set()
    result: list[Mirror] = []
    for mirror in candidates:
        if mirror.url in seen:
            continue
        seen.add(mirror.url)
        result.append(mirror)
    return result


def build_candidates(
    snapshot: MirrorStatusSnapshot,
    *,
    target_country: str,
    config: Config,
    now: float | None = None,
) -> list[Mirror]:
    eligible = eligible_mirrors(
        snapshot,
        min_completion=config.mirror_min_completion,
        max_delay_hours=config.mirror_max_delay_hours,
        max_age_hours=config.mirror_max_age_hours,
        now=now,
    )
    country_mirrors = sorted(
        mirrors_for_country(eligible, target_country), key=lambda item: item.rank_key
    )[: config.mirror_global_candidates]
    global_mirrors = sorted(eligible, key=lambda item: item.rank_key)[
        : config.mirror_global_candidates
    ]
    return _dedupe_candidates(country_mirrors + global_mirrors)


HTTPS_PREFERENCE_RATIO = 1.15


def _preferred_result(results: list[ProbeResult]) -> ProbeResult:
    """Pick the best protocol for one host, preferring HTTPS when close."""
    results.sort(
        key=lambda result: (
            result.latency_ms if result.latency_ms is not None else 1e12,
            0 if result.mirror.protocol == "https" else 1,
            result.mirror.url,
        )
    )
    best = results[0]
    if best.latency_ms is None:
        return best
    https = [
        result
        for result in results
        if result.mirror.protocol == "https"
        and result.latency_ms is not None
        and result.latency_ms <= best.latency_ms * HTTPS_PREFERENCE_RATIO
    ]
    if https:
        return min(https, key=lambda result: result.latency_ms or 0.0)
    return best


def select_results(results: Iterable[ProbeResult], limit: int) -> list[Mirror]:
    by_host: dict[str, list[ProbeResult]] = {}
    for result in results:
        if not result.ok or result.latency_ms is None:
            continue
        host = result.mirror.host
        if not host:
            continue
        by_host.setdefault(host, []).append(result)
    ranked = sorted(
        (_preferred_result(items) for items in by_host.values()),
        key=lambda result: (
            round(result.latency_ms or 0.0, 1),
            result.mirror.score if result.mirror.score is not None else 10_000.0,
            result.mirror.url,
        ),
    )
    return [result.mirror for result in ranked[:limit]]


def render_mirrorlist(
    selected: Iterable[Mirror],
    *,
    target_country: str,
    target_source: str,
    measured_at: float,
    latencies: dict[str, float] | None = None,
) -> str:
    latencies = latencies or {}
    stamp = time.strftime("%Y-%m-%d %H:%M:%S %Z", time.localtime(measured_at))
    country = normalize_code(target_country)
    lines = [
        "##",
        "## Arch Linux repository mirrorlist",
        "## Generated by proton-net-optimizer (pno).",
        f"## Target country: {country} ({country_name(country)}) via {target_source}",
        f"## Measured: {stamp}",
        "## Ranked by measured latency from this network.",
        "##",
        "",
    ]
    for mirror in selected:
        latency = latencies.get(mirror.url)
        if latency is not None:
            lines.append(f"# {mirror.host}: {latency:.0f} ms")
        lines.append(mirror.server_line)
    lines.append("")
    return "\n".join(lines)


def plan_mirrors(
    snapshot: MirrorStatusSnapshot,
    *,
    target_country: str,
    target_source: str,
    config: Config,
    probe: Callable[..., list[ProbeResult]] = probe_many,
    now: float | None = None,
) -> MirrorPlan:
    timestamp = now if now is not None else time.time()
    country = normalize_code(target_country)
    candidates = build_candidates(
        snapshot, target_country=country, config=config, now=timestamp
    )
    events.emit(
        "info",
        "mirrors",
        "mirrors.plan.started",
        {
            "country": country,
            "source": target_source,
            "candidates": len(candidates),
        },
    )
    if not candidates:
        raise ProbeError(
            "no eligible mirrors",
            detail=f"country={country}",
            hint="Check network connectivity and the Arch mirror status.",
        )
    results = probe(
        candidates,
        timeout=config.mirror_probe_timeout,
        attempts=config.mirror_probe_attempts,
    )
    selected = select_results(results, config.mirror_count)
    if not selected:
        failures = sum(1 for result in results if not result.ok)
        raise ProbeError(
            "no mirror passed the latency probe",
            detail=f"{failures}/{len(results)} candidates failed",
        )
    latencies = {
        result.mirror.url: result.latency_ms
        for result in results
        if result.ok and result.latency_ms is not None
    }
    content = render_mirrorlist(
        selected,
        target_country=country,
        target_source=target_source,
        measured_at=timestamp,
        latencies=latencies,
    )
    plan = MirrorPlan(
        target_country=country,
        target_source=target_source,
        candidates=list(results),
        selected=selected,
        content=content,
        measured_at=timestamp,
    )
    events.emit(
        "info",
        "mirrors",
        "mirrors.plan.done",
        {
            "country": country,
            "selected": len(selected),
            "candidates": len(results),
            "hosts": [mirror.host for mirror in selected],
        },
    )
    return plan
